'use strict';
const assert=require('node:assert/strict'),path=require('node:path');
const {fixture}=require('./translation-publication-fixture');
const {assemble}=require('../../tools/deepdive-stage2/lib/translation-publication');
const {verifyTranslationBrowser}=require('../../tools/deepdive-stage2/lib/translation-browser-verifier');
(async()=>{
  const f=fixture(),candidate=assemble(f),root=path.resolve(__dirname,'../..');
  const receipt=await verifyTranslationBrowser(root,candidate,f.snapshot.capture.page);
  assert.equal(receipt.artifactHash,candidate.artifactHash);assert.equal(receipt.browserChecks.length,9);
  assert(receipt.browserChecks.every(c=>c.passed));assert.equal(receipt.kind,'automated-browser-resource-v1');
  const {isLocalLayoutStyle}=require('../../tools/deepdive-stage2/lib/translation-local-style');
  const localStyle={tag:'div',attribute:'style',value:'display:flex;flex-wrap:wrap;gap:12px;align-items:flex-start',status:'requires-resource-review'};
  assert(isLocalLayoutStyle(localStyle));
  assert(isLocalLayoutStyle({...localStyle,tag:'svg',value:'flex:1 1 190px;min-width:190px;max-width:100%;height:auto;display:block'}));
  assert(isLocalLayoutStyle({...localStyle,tag:'p',value:'font-size:0.85em'}));
  for(const value of ['background:url(https://example.com/image)', 'display:var(--x)', 'display:flex/*comment*/', 'display:f\\6cex', 'behavior:url(x)', 'height:expression(x)', 'height:attr(data-size)', 'unknown:1', '']) assert(!isLocalLayoutStyle({...localStyle,value}),value);
  assert(!isLocalLayoutStyle({...localStyle,attribute:'src'}));
  const styled=structuredClone(candidate),styledSource=structuredClone(f.snapshot.capture.page);
  styled.payload.dependencies=[localStyle];
  for(const page of [styled.payload.page,styledSource])page.html='<div style="'+localStyle.value+'"><p>Layout</p></div>'+page.html;
  assert((await verifyTranslationBrowser(root,styled,styledSource)).browserChecks.every(c=>c.passed));
  const remoteStyle=structuredClone(styled);remoteStyle.payload.dependencies[0].value='background:url(https://example.com/image)';
  await assert.rejects(verifyTranslationBrowser(root,remoteStyle,styledSource),/Unresolved resource/);
  const raster=structuredClone(candidate);raster.payload.page.html+='<img src="image.png">';
  await assert.rejects(verifyTranslationBrowser(root,raster,f.snapshot.capture.page),/visual review/);
  const speech=structuredClone(candidate),source=structuredClone(f.snapshot.capture.page);
  speech.payload.pageId='speech';
  source.html+='<p>三百、三元、银行、行走</p>';
  speech.payload.page.html+='<p>Expand numbers (三百), resolve abbreviations (3元 as 三元), and select pronunciation of 行 in 银行 and 行走.</p>';
  const speechReceipt=await verifyTranslationBrowser(root,speech,source);
  assert.equal(speechReceipt.literalTeachingExamples.pageId,'speech');
  speech.payload.page.html+='<p>未翻译的说明</p>';
  await assert.rejects(verifyTranslationBrowser(root,speech,source),/untranslated-visible-text/);
  const tool=structuredClone(candidate),toolSource=structuredClone(f.snapshot.capture.page);
  tool.payload.pageId='tool-calling';
  toolSource.html+='<code>get_weather("北京");send_notification("北京32°C")</code>';
  tool.payload.page.html+='<p>Call get_weather("北京") and send_notification("北京32°C").</p>';
  assert.equal((await verifyTranslationBrowser(root,tool,toolSource)).literalTeachingExamples.pageId,'tool-calling');
  tool.payload.page.html+='<p>北京是城市</p>';
  await assert.rejects(verifyTranslationBrowser(root,tool,toolSource),/untranslated-visible-text/);
  console.log('PASS actual Edge desktop/mobile, navigation, language stability and conservative resource gate (synthetic page)');
})().catch(e=>{console.error(e);process.exitCode=1;});
