'use strict';
const assert=require('node:assert/strict');
const batches=require('../../tools/deepdive-stage2/lib/translation-review-batches');
const units=Array.from({length:125},(_,i)=>({key:'section/u'+i,kind:'text',source:'原文 '+i,translation:'Source '+i}));
const plan=batches.plan('revision-a',units);
assert.deepEqual(plan.map(b=>b.unitKeys.length),[60,60,5,0]);
assert.deepEqual(plan.slice(0,-1).flatMap(b=>b.unitKeys),units.map(u=>u.key));
assert.notEqual(plan[0].batchId,batches.plan('revision-b',units)[0].batchId);
const response=b=>({batchId:b.batchId,checkedUnitKeys:b.unitKeys,findings:[],summary:b.phase==='consistency'?'All references were compared across chapters.':''});
for(const b of plan)batches.validate(b,response(b),units);
assert.throws(()=>batches.validate(plan[0],{...response(plan[0]),checkedUnitKeys:plan[0].unitKeys.slice(1)},units),/coverage/);
assert.throws(()=>batches.validate(plan[1],response(plan[0]),units),/batch/);
const f={rule:7,unitKey:units[0].key,sourceQuote:units[0].source,translationQuote:units[0].translation,reason:'Negation omitted.',mqmCategory:'accuracy/omission',severity:'major'};
batches.validate(plan[0],{...response(plan[0]),findings:[f]},units);
batches.validate(plan[1],{...response(plan[1]),findings:[f]},units);
assert.throws(()=>batches.validate(plan[1],{...response(plan[1]),findings:[{...f,unitKey:'other-page/u1'}]},units),/outside/);
assert.throws(()=>batches.validate(plan[0],{...response(plan[0]),findings:[{...f,translationQuote:'fabricated'}]},units),/Ungrounded/);
assert.throws(()=>batches.validate(plan.at(-1),{...response(plan.at(-1)),summary:''},units),/summary/);
const packet=batches.packet('revision-a',units,[],{glossary:{},sourceHtml:'<p>source</p>'});
const raw={completed:true,findings:[f],wholePageRationale:''};
const normalized=batches.normalizeResponse(packet,raw);
batches.validate(plan[0],normalized.evidence,units);
assert(raw.wholePageRationale==='');assert(!raw.batchId);
assert.equal(normalized.normalization.length,2);
for(const rule of ['4','7','8']){
 const rawString={completed:true,findings:[{...f,rule,mqmCategory:rule==='4'?'terminology':rule==='8'?'accuracy/consistency':f.mqmCategory}],summary:''};
 const result=batches.normalizeResponse(packet,rawString);
 batches.validate(plan[0],result.evidence,units);
 assert.equal(result.evidence.findings[0].rule,Number(rule));assert.equal(rawString.findings[0].rule,rule);
}
for(const rule of ['5','07','7.0','7 junk',true])assert.throws(()=>batches.validate(plan[0],batches.normalizeResponse(packet,{completed:true,findings:[{...f,rule}],summary:''}).evidence,units),/Invalid defect explanation/);
const aliasFinding={...f,'exact sourceQuote':f.sourceQuote,'exact translationQuote':f.translationQuote};
delete aliasFinding.sourceQuote;delete aliasFinding.translationQuote;
const aliased={completed:true,findings:[aliasFinding],summary:''};
const recovered=batches.normalizeResponse(packet,aliased);
batches.validate(plan[0],recovered.evidence,units);
assert.equal(aliased.findings[0]['exact sourceQuote'],f.sourceQuote);
assert.throws(()=>batches.normalizeResponse(packet,{...aliased,findings:[{...aliasFinding,sourceQuote:'conflict'}]}),/Conflicting quote aliases/);
assert.throws(()=>batches.validate(plan[0],batches.normalizeResponse(packet,{...aliased,findings:[{...aliasFinding,'exact translationQuote':'fabricated'}]}).evidence,units),/Ungrounded/);
assert.throws(()=>batches.normalizeResponse(packet,{completed:false,findings:[],summary:''}),/completed/);
assert.throws(()=>batches.normalizeResponse(packet,{findings:[],summary:''}),/completed/);
assert.equal(packet.pageContext.length,125);assert(!packet.sourceHtml);assert(!packet.outputContract);
assert.equal(batches.packet('revision-a',units,plan.slice(0,3),{sourceHtml:'<p>source</p>'}).sourceHtml,'<p>source</p>');
const long=units.slice(0,3).map(u=>({...u,translation:'x'.repeat(7000)}));assert.equal(batches.plan('r',long).length,4);
// Output-size comparison, synthetic fixture, not measured provider latency.
const old={checkedUnits:Object.fromEntries(units.map(u=>[u.key,[u.source,u.translation,'The translation preserves the meaning and qualifications of this source unit.']])),findings:[],wholePageRationale:'All references were compared across chapters.'};
const oldBytes=Buffer.byteLength(JSON.stringify(old)),newBytes=plan.reduce((n,b)=>n+Buffer.byteLength(JSON.stringify(response(b))),0);
assert(newBytes<oldBytes*.3);
console.log(`PASS bounded batches, revision/scope/quote guards, full context; synthetic clean report bytes ${oldBytes} -> ${newBytes}`);
