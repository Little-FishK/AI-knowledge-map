"use strict";
const assert=require('node:assert/strict');
const {sanitizedGateDiagnostic}=require('../../tools/deepdive-stage2/lib/candidate-gate');
const r=sanitizedGateDiagnostic({script:'gate.js',passed:false,output:'✗ L3 参照页哈希漂移：private values\nprivate audit answer should never be exposed\nTypeError: Cannot read properties of undefined (reading \'items\')'});
assert.equal(r.referenceHashDrift,true);assert.equal(r.exceptionType,'TypeError');assert.equal(r.propertyName,'items');
