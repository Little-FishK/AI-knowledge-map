console.log('✓ Reference drift remains blocked without directing content rewrites');
const {previewReferenceBenchmark}=require('../../tools/deepdive-stage2/lib/candidate-gate');
const before={reference:{id:'reference',pageHash:'sha256:'+'a'.repeat(64)},minimumScore:90,dimensionFloors:{mechanism:8}};
const after=previewReferenceBenchmark(before,'reference','sha256:'+'b'.repeat(64));
