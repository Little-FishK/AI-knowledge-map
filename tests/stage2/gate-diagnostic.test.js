assert.equal(m.missingModule,'missing.js');assert(!JSON.stringify(m).includes('secrets'));
assert.equal(sanitizedGateDiagnostic({script:'gate.js',passed:true,output:'success'}).referenceHashDrift,false);
console.log('✓ Sanitized gate diagnostics preserve categories and omit raw audit/process output');
const {createCandidateGate}=require('../../tools/deepdive-stage2/lib/candidate-gate');
const gate=createCandidateGate({});
const defects=gate.gateDefects({script:'l3.js',output:'L3 参照页哈希漂移：private hash and audit text'},'supervised-learning');
assert.equal(defects.length,1);
assert.equal(defects[0].type,'gate');
assert.equal(defects[0].code,'reference-hash-drift');
assert(!JSON.stringify(defects).includes('private'));
assert(!JSON.stringify(defects).includes('读者可见缺口'));
