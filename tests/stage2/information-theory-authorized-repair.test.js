"use strict";
const assert=require('node:assert/strict');
const {repairPage,createAuthorizedRepair,SOURCE,APPROVED_HASH}=require('../../tools/deepdive-stage2/lib/information-theory-authorized-repair');
const original={title:'Synthetic fixture',quality:{keep:true},html:Array.from({length:8},(_,i)=>`<section><h2>${i+1}</h2>${i===7?'<figure><svg><text>D<sub>KL</sub>(P||Q)</text><text>0.1038 bit</text></svg></figure>':'unchanged'}</section>`).join('')+'<div class="dd-src"><a href="https://example.com">Existing</a></div>'};
const page=repairPage(original);
assert.deepEqual(page.quality,original.quality);
assert(page.html.includes('<tspan baseline-shift="sub" font-size="75%">KL</tspan>'));
assert(page.html.includes('<text>0.1038 bit</text>'));
assert(page.html.includes(SOURCE));
assert(original.html.includes('<sub>KL</sub>'));
const reversed=page.html.replace('<tspan baseline-shift="sub" font-size="75%">KL</tspan>','<sub>KL</sub>').replace(/<p><a href="https:\/\/huggingface.co\/docs\/transformers\/perplexity"[\s\S]*?<\/p>/,'');
assert.equal(reversed,original.html);
assert.throws(()=>repairPage(page));
assert.throws(()=>repairPage({...original,html:original.html.replace('D<sub>KL</sub>','D<sub>XX</sub>')}));
let released=0,written=0;
const d={acquireLock:()=>()=>released++,loadState:()=>({pages:{'information-theory':{state:'repair-queued',lease:{}}}}),writeJson:()=>written++};
assert.throws(()=>createAuthorizedRepair(d)('fixture',APPROVED_HASH),/Active lease/);
d.loadState=()=>({pages:{'information-theory':{state:'repair-queued'}}});d.currentPage=()=>original;
assert.throws(()=>createAuthorizedRepair(d)('fixture',APPROVED_HASH),/candidate changed/);
assert.equal(released,2);assert.equal(written,0);
console.log('✓ Limited repair preserves unrelated content and rejects drift, duplicate use and active leases');
