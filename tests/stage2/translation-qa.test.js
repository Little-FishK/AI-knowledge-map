'use strict';
const assert=require('node:assert/strict');
const {validClassification,summarize}=require('../../tools/deepdive-stage2/lib/translation-qa');
assert(!validClassification({rule:7},true));
assert(validClassification({rule:7}));
assert(!validClassification({rule:7,mqmCategory:'terminology',severity:'minor'},true));
assert(!validClassification({rule:4,mqmCategory:'terminology',severity:'pass'},true));
assert(validClassification({rule:7,mqmCategory:'accuracy/omission',severity:'critical'},true));
const gates=Array.from({length:9},(_,i)=>({number:i+1,status:'pass'}));
gates[8].status='pending-stage9-browser-test';
const result=summarize(gates,[]);
assert.equal(result.layers.find(x=>x.name==='presentation').status,'pending');
assert.equal(result.layers.find(x=>x.name==='semantic').status,'pass');
assert.equal(summarize([],[]).layers.every(x=>x.status==='pending'),true);
const {failure}=require('../../tools/deepdive-stage2/lib/translation-error');
assert.equal(failure(Error('browser executable missing'),'publication').layer,'system');
assert.equal(failure(Error('SVG text exceeds its canvas'),'publication').layer,'presentation');
assert.equal(failure(Error('Review evidence failed validation'),'quality').countsAsSemanticDefect,false);
console.log('PASS MQM category validation, legacy compatibility and separated pending presentation');
