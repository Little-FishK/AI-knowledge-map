'use strict';
const assert=require('node:assert/strict');
const {failure}=require('../../tools/deepdive-stage2/lib/translation-error');
const {resourceLayout}=require('../../tools/readiness/render-english-pilot');
const error=Error('Provider failed with Bearer token-secret and private-api-value');
const logged=failure(error,'quality',{DEEPSEEK_API_KEY:'private-api-value'});
assert(!logged.message.includes('private-api-value'));assert(!logged.message.includes('token-secret'));
assert.equal(logged.phase,'quality');assert(logged.at);
const label='Independent evaluation finds over-refusal/misinterpretation → revise the principles, examples, or feedback model; do not just add stronger wording';
const svg=`<svg viewBox="0 0 680 245"><text x="433" y="210" text-anchor="middle" class="svg-t" font-size="10">${label}</text></svg>`;
const rendered=resourceLayout(svg,{splitLegend:false});
assert.equal((rendered.match(/<tspan/g)||[]).length,2);
assert.equal([...rendered.matchAll(/<tspan[^>]*>(.*?)<\/tspan>/g)].map(m=>m[1]).join(''),label);
assert(svg.includes('x="433"'));assert(rendered.includes('x="340"'));
const different=svg.replace('680 245','681 245');
assert(resourceLayout(different,{splitLegend:false}).includes(different));
const density='<svg viewBox="0 0 735 310"><text x="375" y="75" class="svg-t">Density: reachable in neighborhood; sparse points can be labeled as noise</text></svg>';
assert(resourceLayout(density,{splitLegend:false}).includes('style="font-size:10px"'));
const axis='<svg viewBox="0 0 700 270"><text x="550" y="248" class="svg-tn">Regularization strength λ</text></svg>';
assert(resourceLayout(axis,{splitLegend:false}).includes('x="520" y="248"'));
assert.equal(axis.replace(/<[^>]+>/g,''),resourceLayout(axis,{splitLegend:false}).split('</svg>')[0].replace(/<[^>]+>/g,''));
const voice='<figure><svg viewBox="0 0 760 285"><text x="81" y="183">Authorized reference recording</text><text x="671" y="171">Governance</text></figure>';
const voiceRendered=resourceLayout(voice,{splitLegend:false});
assert(voiceRendered.includes('x="90" y="183"'));assert(voiceRendered.includes('x="646" y="171"'));
assert(voiceRendered.includes('</svg>'));assert(voiceRendered.includes('preview-diagram-scroll'));
console.log('PASS sanitized errors and exact-text SVG caption layout with unknown diagrams unchanged');
