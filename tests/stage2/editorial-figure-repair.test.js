"use strict";
const assert = require("assert/strict");
const { figureRepairBaseline } = require("../../tools/deepdive-stage2/lib/editorial-figure-repair");
const { pageContentHash } = require("../../tools/deepdive/quality/deepdive-audit-contracts");
const source = { title: "Fixture", html: '<section><figure class="dd-fig">first</figure></section><section><figure class="dd-fig"><svg><path d="old"/></svg></figure></section>' };
const candidate = { ...source, html: source.html.replace('d="old"', 'd="new"') };
const record = { id: "fixture", lease: { role: "repair" }, repairAttempts: 0, editorialWorkflow: { requiresHumanReview: true, maxRepairAttempts: 1, initialBlockingFindings: [{ findingId: "finding", section: 2, code: "image-text-mismatch" }] } };
const grant = { pageId: "fixture", candidateHash: pageContentHash(source), findingId: "finding", section: 2 };
const run = (r = record, s = source, c = candidate, g = grant) => figureRepairBaseline(r, s, c, JSON.stringify(g));
assert.equal(run().baseline.html, candidate.html);
assert.equal(run().receipt.authorization.candidateHash, grant.candidateHash);
assert.notEqual(run().receipt.beforeFigureHash, run().receipt.afterFigureHash);
assert.equal(figureRepairBaseline(record, source, candidate, "").baseline, source);
assert.throws(() => run({ ...record, repairAttempts: 1 }), /single/);
assert.throws(() => run({ ...record, lease: { role: "audit" } }), /single/);
assert.throws(() => run(record, { ...source, title: "changed" }), /source changed/);
assert.throws(() => run(record, source, candidate, { ...grant, pageId: "other" }), /source changed/);
assert.throws(() => run(record, source, candidate, { ...grant, findingId: "other" }), /first-audit/);
assert.throws(() => run(record, source, { ...candidate, html: candidate.html.replace("first", "tampered") }), /unauthorized/);
assert.throws(() => run(record, source, { ...candidate, html: candidate.html.replace('<path d="new"/>', '<script>bad</script>') }), /Unsafe/);
assert.throws(() => run(record, source, source), /must change/);
assert.throws(() => run(record, source, { ...candidate, html: candidate.html.replace('</figure></section>', '</figure><figure class="dd-fig">extra</figure></section>') }));
console.log("PASS single-round figure repair source/finding scope, unchanged other figures, unsafe markup and exhausted-round rejection");
