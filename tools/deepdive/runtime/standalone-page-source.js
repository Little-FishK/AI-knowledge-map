"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const PAGE_ID_PATTERN = /^[a-z0-9][a-z0-9-]*$/;

function assertPageId(id) {
  if (!PAGE_ID_PATTERN.test(id)) {
    throw new Error(`无效的理解原理页 ID：${id}`);
  }
}

function normalizePage(page, label = "理解原理页") {
  if (!page || typeof page !== "object" || Array.isArray(page)) {
    throw new Error(`${label}必须是普通对象`);
  }
  let serialized;
  try {
    serialized = JSON.stringify(page);
  } catch (error) {
    throw new Error(`${label}无法完整序列化：${error.message}`);
  }
  if (serialized === undefined) throw new Error(`${label}无法完整序列化`);
  return JSON.parse(serialized);
}

function pageRegistrationSource(id, page, banner = "Generated by the Stage 2 controller. Do not edit by hand.") {
  assertPageId(id);
  const normalized = normalizePage(page, `页面 ${id}`);
  return [
    `/* ${banner} */`,
    "window.DEEPDIVE = window.DEEPDIVE || {};",
    `window.DEEPDIVE[${JSON.stringify(id)}] = ${JSON.stringify(normalized, null, 2)};`,
    "",
  ].join("\n");
}

function standaloneLayoutSource(pageCount) {
  if (!Number.isInteger(pageCount) || pageCount < 0) throw new Error("独立理解原理页数量无效");
  return `${JSON.stringify({ schemaVersion: 1, mode: "standalone-page", pageCount }, null, 2)}\n`;
}

function loadStandalonePageSource(source, filename, expectedId = path.basename(filename, path.extname(filename))) {
  assertPageId(expectedId);
  const context = { window: {} };
  vm.createContext(context);
  vm.runInContext(source, context, { filename });
  const registry = context.window.DEEPDIVE;
  if (!registry || typeof registry !== "object" || Array.isArray(registry)) {
    throw new Error(`${filename}: 必须创建 window.DEEPDIVE 并注册页面`);
  }
  const ids = Object.keys(registry);
  if (ids.length !== 1) {
    throw new Error(`${filename}: 必须且只能注册一个页面（当前 ${ids.length}）`);
  }
  if (ids[0] !== expectedId) {
    throw new Error(`${filename}: 注册 ID ${ids[0]} 与文件名 ${expectedId} 不一致`);
  }
  return normalizePage(registry[expectedId], `页面 ${expectedId}`);
}

function loadStandalonePageFile(file) {
  const id = path.basename(file, path.extname(file));
  return {
    id,
    page: loadStandalonePageSource(fs.readFileSync(file, "utf8"), file, id),
  };
}

function loadStandalonePageDirectory(directory, options = {}) {
  const filenames = (options.filenames || fs.readdirSync(directory))
    .filter(file => file.endsWith(".js"));
  const pages = Object.create(null);
  const caseInsensitiveIds = new Map();
  filenames.forEach(filename => {
    const fullPath = path.join(directory, filename);
    const { id, page } = loadStandalonePageFile(fullPath);
    const folded = id.toLowerCase();
    if (caseInsensitiveIds.has(folded)) {
      throw new Error(`理解原理页 ID 大小写冲突：${caseInsensitiveIds.get(folded)} / ${id}`);
    }
    if (Object.prototype.hasOwnProperty.call(pages, id)) {
      throw new Error(`理解原理页重复注册：${id}`);
    }
    caseInsensitiveIds.set(folded, id);
    pages[id] = page;
  });
  return pages;
}

module.exports = {
  assertPageId,
  loadStandalonePageDirectory,
  loadStandalonePageFile,
  loadStandalonePageSource,
  normalizePage,
  pageRegistrationSource,
  standaloneLayoutSource,
};
